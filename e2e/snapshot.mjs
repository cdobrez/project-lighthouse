import { chromium } from "playwright-core";
// Two instances sharing one SNAPSHOT_DIR: start them on 3011 and 3012 before running this.
const launch = { args: ["--no-sandbox"] };
if (process.env.CHROME_PATH) launch.executablePath = process.env.CHROME_PATH;
const browser = await chromium.launch(launch);
const A = "http://localhost:3011", B = "http://localhost:3012";
const stamp = Date.now();
const pa = await (await browser.newContext()).newPage();
await pa.goto(`${A}/signup`);
await pa.fill("#name", "Snap Tester"); await pa.fill("#email", `snap${stamp}@example.com`); await pa.fill("#password", "neighbor123");
await pa.click("button[type=submit]"); await pa.waitForURL("**/meals");
console.log("signed up on A");
await pa.goto(`${A}/meals/nonnas-baked-lasagna`);
await pa.locator("aside button", { hasText: "Add to basket" }).click();
await pa.goto(`${A}/checkout`); await pa.click("button:has-text('Place order')"); await pa.waitForURL("**/orders/*");
console.log("ordered on A");
await new Promise((r) => setTimeout(r, 4500));
const pb = await (await browser.newContext()).newPage();
await pb.goto(`${B}/login`);
await pb.fill("#email", `snap${stamp}@example.com`); await pb.fill("#password", "neighbor123"); await pb.click("button[type=submit]");
await pb.waitForURL("**/meals");
console.log("logged in on B with the account created on A");
await pb.goto(`${B}/orders`);
await pb.waitForSelector("text=Nonna");
console.log("B sees the order placed on A");
await pb.goto(`${B}/community`);
await pb.click("label:has-text('Story')");
await pb.fill("input[name=title]", `Cross-instance post ${stamp}`);
await pb.fill("textarea[name=body]", "Written on instance B, should appear on instance A.");
await pb.click("button:has-text('Post')"); await pb.waitForSelector("text=Posted to the");
await new Promise((r) => setTimeout(r, 4500));
await pa.goto(`${A}/community`);
await pa.waitForSelector(`text=Cross-instance post ${stamp}`);
console.log("A sees the post written on B");
console.log("SNAPSHOT OK");
await browser.close();
