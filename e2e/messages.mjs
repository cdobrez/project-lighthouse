import { chromium } from "playwright-core";
const launch = { args: ["--no-sandbox"] };
if (process.env.CHROME_PATH) launch.executablePath = process.env.CHROME_PATH;
const browser = await chromium.launch(launch);
const p = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const B = process.env.BASE ?? "http://localhost:3000";
async function login(email) { await p.goto(`${B}/login`); await p.fill("#email", email); await p.fill("#password", "neighbor123"); await p.click("button[type=submit]"); await p.waitForURL("**/meals"); }
async function logout() { await p.goto(`${B}/account`); await p.click("button:has-text('Sign out')"); await p.waitForURL(`${B}/`); }
await login("demo@gigkitchens.com");
await p.goto(`${B}/orders`);
await p.locator("a[href^='/orders/ord_']").filter({ hasText: "Herb Roast Chicken" }).first().click();
await p.waitForURL("**/orders/ord_*");
const orderUrl = p.url();
await p.fill("input[name=body]", "Can you leave it by the side door? Dog is friendly but loud.");
await p.click("button:has-text('Send')");
await p.waitForSelector("text=Dog is friendly");
console.log("customer sent message");
await logout();
await login("hannah@example.com");
await p.goto(`${B}/cook`);
await p.waitForSelector("text=1 new message");
console.log("cook sees unread badge");
await p.click("text=Details & messages");
await p.waitForURL("**/cook/orders/ord_*");
await p.waitForSelector("text=Dog is friendly");
await p.fill("input[name=body]", "Side door it is. Ready at 5:30!");
await p.click("button:has-text('Send')");
await p.waitForSelector("text=Side door it is");
await p.screenshot({ path: "e2e/screenshots/cook-order-thread.png", fullPage: true });
await p.goto(`${B}/cook`);
console.log("badge cleared for cook:", (await p.locator("text=new message").count()) === 0);
await logout();
await login("demo@gigkitchens.com");
await p.goto(`${B}/orders`);
await p.waitForSelector("text=1 new");
console.log("customer sees unread badge");
await p.goto(orderUrl);
await p.waitForSelector("text=Side door it is");
await p.screenshot({ path: "e2e/screenshots/order-thread.png", fullPage: true });
console.log("MESSAGES OK");
await browser.close();
