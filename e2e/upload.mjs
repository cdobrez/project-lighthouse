import { chromium } from "playwright-core";
const launch = { args: ["--no-sandbox"] };
if (process.env.CHROME_PATH) launch.executablePath = process.env.CHROME_PATH;
const browser = await chromium.launch(launch);
const p = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const B = process.env.BASE ?? "http://localhost:3000";
await p.goto(`${B}/login`); await p.fill("#email", "rosa@example.com"); await p.fill("#password", "neighbor123"); await p.click("button[type=submit]"); await p.waitForURL("**/meals");
await p.goto(`${B}/cook/meals/new`);
await p.fill("#title", "Upload Test Focaccia");
await p.fill("#price", "7");
await p.fill("#description", "Rosemary focaccia baked this morning, still warm when you pick it up.");
await p.fill("#cuisine", "Italian");
await p.click("label:has-text('Sat')");
await p.setInputFiles("input[type=file]", "public/images/meal-minestrone.jpg");
await p.waitForFunction(() => { const i = document.querySelector('input[name="imageKey"]'); return i && i.value.startsWith("/api/uploads/"); }, null, { timeout: 20000 });
const url = await p.inputValue('input[name="imageKey"]');
console.log("uploaded ->", url);
await p.click("button:has-text('List this meal')");
await p.waitForURL("**/cook/meals");
await p.goto(`${B}/meals/upload-test-focaccia`);
const img = await p.locator("img[alt='Upload Test Focaccia']").first().getAttribute("src");
console.log("meal page image src:", img);
const r = await p.request.get(`${B}${url}`);
console.log("upload served:", r.status(), r.headers()["content-type"]);
await p.goto(`${B}/cook/profile`);
await p.setInputFiles("input[type=file]", "public/images/cook-rosa.jpg");
await p.waitForFunction(() => { const i = document.querySelector('input[name="imageKey"]'); return i && i.value.startsWith("/api/uploads/"); }, null, { timeout: 20000 });
await p.click("button:has-text('Save profile')");
await p.waitForSelector("text=Profile saved");
await p.goto(`${B}/cooks/rosas-kitchen`);
const portrait = await p.locator("img[alt=\"Rosa's Kitchen\"]").first().getAttribute("src");
console.log("cook portrait src:", portrait);
await browser.close();
