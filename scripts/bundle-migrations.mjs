// Bundles drizzle/*.sql into src/lib/db/migrations.ts so migrations ship inside the
// server bundle and run on any host (Vercel, Docker, local) without filesystem access.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "drizzle");
const journal = JSON.parse(readFileSync(join(dir, "meta", "_journal.json"), "utf8"));
const files = readdirSync(dir).filter((f) => f.endsWith(".sql"));
const entries = journal.entries.map((e) => {
  const file = files.find((f) => f.startsWith(e.tag));
  if (!file) throw new Error(`Missing SQL for migration ${e.tag}`);
  const sql = readFileSync(join(dir, file), "utf8");
  const statements = sql
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { name: e.tag, statements };
});
const out = `// Generated by scripts/bundle-migrations.mjs. Do not edit; run \`npm run db:generate\`.
export type Migration = { name: string; statements: string[] };
export const MIGRATIONS: Migration[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(process.cwd(), "src/lib/db/migrations.ts"), out);
console.log(`Bundled ${entries.length} migrations.`);
